// CM FLIX native secret store.
//
// The AES key material lives here in compiled ARM machine code instead of
// in the dex file, so plain dex string inspection (MT Manager, jadx, ...)
// cannot reveal it. The four key parts are additionally XOR-masked so that
// even a raw `strings` pass over the .so file shows nothing useful.
//
// Security note: this raises the bar from "dex reader" to "native reverser"
// (IDA/Ghidra + ARM). A native anti-tamper gate (debugger / Frida /
// signature verification) additionally fails closed on re-signed or
// instrumented copies. It does not make client-side secrets unrecoverable;
// nothing can, as long as the app itself must decrypt them offline.

#include <stdint.h>
#include <stdlib.h>
#include <string.h>

#ifdef __ANDROID__
#include <jni.h>
#endif

// ---------------------------------------------------------------------------
// SHA-256 (public-domain style implementation)
// ---------------------------------------------------------------------------

#include "sha256_tables.inc"  // K[64], H0[8] generated by script, verified

#define ROTR(x, n) (((x) >> (n)) | ((x) << (32 - (n))))

static void sha256_block(const uint8_t *p, uint32_t h[8]) {
    uint32_t w[64];
    for (int i = 0; i < 16; i++) {
        w[i] = ((uint32_t)p[i * 4] << 24) | ((uint32_t)p[i * 4 + 1] << 16) |
               ((uint32_t)p[i * 4 + 2] << 8) | (uint32_t)p[i * 4 + 3];
    }
    for (int i = 16; i < 64; i++) {
        uint32_t s0 = ROTR(w[i - 15], 7) ^ ROTR(w[i - 15], 18) ^ (w[i - 15] >> 3);
        uint32_t s1 = ROTR(w[i - 2], 17) ^ ROTR(w[i - 2], 19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16] + s0 + w[i - 7] + s1;
    }
    uint32_t a = h[0], b = h[1], c = h[2], d = h[3];
    uint32_t e = h[4], f = h[5], g = h[6], hh = h[7];
    for (int i = 0; i < 64; i++) {
        uint32_t S1 = ROTR(e, 6) ^ ROTR(e, 11) ^ ROTR(e, 25);
        uint32_t ch = (e & f) ^ (~e & g);
        uint32_t t1 = hh + S1 + ch + K[i] + w[i];
        uint32_t S0 = ROTR(a, 2) ^ ROTR(a, 13) ^ ROTR(a, 22);
        uint32_t maj = (a & b) ^ (a & c) ^ (b & c);
        uint32_t t2 = S0 + maj;
        hh = g; g = f; f = e; e = d + t1;
        d = c; c = b; b = a; a = t1 + t2;
    }
    h[0] += a; h[1] += b; h[2] += c; h[3] += d;
    h[4] += e; h[5] += f; h[6] += g; h[7] += hh;
}

static void sha256(const uint8_t *msg, size_t len, uint8_t out[32]) {
    uint32_t h[8];
    memcpy(h, H0, sizeof(h));
    uint8_t block[64];
    size_t off = 0;
    uint64_t bitlen = (uint64_t)len * 8;
    while (len - off >= 64) {
        sha256_block(msg + off, h);
        off += 64;
    }
    size_t rem = len - off;
    memcpy(block, msg + off, rem);
    block[rem++] = 0x80;
    if (rem > 56) {
        memset(block + rem, 0, 64 - rem);
        sha256_block(block, h);
        rem = 0;
    }
    memset(block + rem, 0, 56 - rem);
    for (int i = 0; i < 8; i++) {
        block[56 + i] = (uint8_t)(bitlen >> (56 - i * 8));
    }
    sha256_block(block, h);
    for (int i = 0; i < 8; i++) {
        out[i * 4] = (uint8_t)(h[i] >> 24);
        out[i * 4 + 1] = (uint8_t)(h[i] >> 16);
        out[i * 4 + 2] = (uint8_t)(h[i] >> 8);
        out[i * 4 + 3] = (uint8_t)h[i];
    }
}

// ---------------------------------------------------------------------------
// AES-128 decrypt (inverse cipher). S-box is computed at startup from the
// GF(2^8) definition so no 256-byte tables need to be transcribed.
// ---------------------------------------------------------------------------

static uint8_t gf_mul(uint8_t a, uint8_t b) {
    uint8_t r = 0;
    while (b) {
        if (b & 1) r ^= a;
        uint8_t hi = a & 0x80;
        a <<= 1;
        if (hi) a ^= 0x1b;
        b >>= 1;
    }
    return r;
}

static uint8_t gf_inv(uint8_t x) {
    if (x == 0) return 0;
    uint8_t r = 1, base = x;
    uint16_t e = 254;
    while (e) {
        if (e & 1) r = gf_mul(r, base);
        base = gf_mul(base, base);
        e >>= 1;
    }
    return r;
}

static uint8_t sbox[256];
static uint8_t rsbox[256];
static int sbox_ready = 0;

static void sbox_init(void) {
    if (sbox_ready) return;
    for (int i = 0; i < 256; i++) {
        uint8_t inv = gf_inv((uint8_t)i);
        uint8_t s = inv ^ (uint8_t)((inv << 1) | (inv >> 7))
                        ^ (uint8_t)((inv << 2) | (inv >> 6))
                        ^ (uint8_t)((inv << 3) | (inv >> 5))
                        ^ (uint8_t)((inv << 4) | (inv >> 4)) ^ 0x63;
        sbox[i] = s;
        rsbox[s] = (uint8_t)i;
    }
    sbox_ready = 1;
}

static uint32_t rcon_for(int i) {
    uint8_t r = 1;
    for (int k = 1; k < i; k++) r = gf_mul(r, 2);
    return (uint32_t)r << 24;
}

static void aes128_keyexpand(const uint8_t key[16], uint8_t rk[11][16]) {
    uint32_t w[44];
    for (int i = 0; i < 4; i++) {
        w[i] = ((uint32_t)key[i * 4] << 24) | ((uint32_t)key[i * 4 + 1] << 16) |
               ((uint32_t)key[i * 4 + 2] << 8) | key[i * 4 + 3];
    }
    sbox_init();
    for (int i = 4; i < 44; i++) {
        uint32_t t = w[i - 1];
        if (i % 4 == 0) {
            t = (t << 8) | (t >> 24);  // RotWord
            t = ((uint32_t)sbox[(t >> 24) & 0xff] << 24) |
                ((uint32_t)sbox[(t >> 16) & 0xff] << 16) |
                ((uint32_t)sbox[(t >> 8) & 0xff] << 8) |
                (uint32_t)sbox[t & 0xff];  // SubWord
            t ^= rcon_for(i / 4);
        }
        w[i] = w[i - 4] ^ t;
    }
    for (int r = 0; r < 11; r++) {
        for (int i = 0; i < 4; i++) {
            rk[r][i * 4] = (uint8_t)(w[r * 4 + i] >> 24);
            rk[r][i * 4 + 1] = (uint8_t)(w[r * 4 + i] >> 16);
            rk[r][i * 4 + 2] = (uint8_t)(w[r * 4 + i] >> 8);
            rk[r][i * 4 + 3] = (uint8_t)w[r * 4 + i];
        }
    }
}

static void add_round_key(uint8_t s[16], const uint8_t rk[16]) {
    for (int i = 0; i < 16; i++) s[i] ^= rk[i];
}

static void inv_shift_rows(uint8_t s[16]) {
    uint8_t t[16];
    for (int row = 0; row < 4; row++) {
        for (int col = 0; col < 4; col++) {
            t[row + 4 * col] = s[row + 4 * ((col - row + 4) % 4)];
        }
    }
    memcpy(s, t, 16);
}

static void inv_sub_bytes(uint8_t s[16]) {
    for (int i = 0; i < 16; i++) s[i] = rsbox[s[i]];
}

static void inv_mix_columns(uint8_t s[16]) {
    for (int c = 0; c < 4; c++) {
        uint8_t a0 = s[c * 4], a1 = s[c * 4 + 1], a2 = s[c * 4 + 2], a3 = s[c * 4 + 3];
        s[c * 4]     = gf_mul(a0, 0x0e) ^ gf_mul(a1, 0x0b) ^ gf_mul(a2, 0x0d) ^ gf_mul(a3, 0x09);
        s[c * 4 + 1] = gf_mul(a0, 0x09) ^ gf_mul(a1, 0x0e) ^ gf_mul(a2, 0x0b) ^ gf_mul(a3, 0x0d);
        s[c * 4 + 2] = gf_mul(a0, 0x0d) ^ gf_mul(a1, 0x09) ^ gf_mul(a2, 0x0e) ^ gf_mul(a3, 0x0b);
        s[c * 4 + 3] = gf_mul(a0, 0x0b) ^ gf_mul(a1, 0x0d) ^ gf_mul(a2, 0x09) ^ gf_mul(a3, 0x0e);
    }
}

static void aes128_ecb_decrypt_block(const uint8_t in[16], uint8_t out[16],
                                     uint8_t rk[11][16]) {
    uint8_t s[16];
    memcpy(s, in, 16);
    add_round_key(s, rk[10]);
    for (int round = 9; round >= 1; round--) {
        inv_shift_rows(s);
        inv_sub_bytes(s);
        add_round_key(s, rk[round]);
        inv_mix_columns(s);
    }
    inv_shift_rows(s);
    inv_sub_bytes(s);
    add_round_key(s, rk[0]);
    memcpy(out, s, 16);
}

// ---------------------------------------------------------------------------
// Key derivation + AES-128-CBC decrypt, mirroring the Gradle build-time
// encryption exactly: key = SHA256(parts+"|k1")[:16],
// iv = SHA256(parts+"|i1")[:16], parts = P2+P0+P3+P1.
// ---------------------------------------------------------------------------

// XOR-masked key parts. The mask is deliberately NOT a compile-time
// constant: it is read through a volatile, which forces the unmasking loop
// to execute at runtime. Otherwise the optimizer constant-folds the XOR
// and stores the assembled secret as plaintext in .rodata (verified via
// `strings` on the built .so). Assembly order below is P2+P0+P3+P1.
static uint8_t xor_mask(void) {
    static volatile uint8_t m = 0x5A;
    return m;
}
static const uint8_t P2M[] = {0x14,0x1f,0x2f,0x33,0x17,0x34,0x3d,0x02,0x3c,0x02};
static const uint8_t P0M[] = {0x20,0x35,0x0e,0x15,0x18,0x6d,0x1b,0x33,0x3e,0x0a};
static const uint8_t P3M[] = {0x3c,0x00,0x0f,0x36,0x62,0x3f,0x23,0x23,0x1e,0x1e};
static const uint8_t P1M[] = {0x2b,0x22,0x17,0x69,0x6b,0x28,0x69,0x19,0x1e,0x2e};

static void derive_key_iv(uint8_t key[16], uint8_t iv[16]) {
    char parts[41];
    const uint8_t *ms[4] = {P2M, P0M, P3M, P1M};
    const uint8_t xm = xor_mask();
    int o = 0;
    for (int k = 0; k < 4; k++) {
        for (int i = 0; i < 10; i++) parts[o++] = (char)(ms[k][i] ^ xm);
    }
    parts[40] = '\0';
    uint8_t digest[32];
    char buf[48];
    memcpy(buf, parts, 40);
    memcpy(buf + 40, "|k1", 3);
    sha256((const uint8_t *)buf, 43, digest);
    memcpy(key, digest, 16);
    memcpy(buf + 40, "|i1", 3);
    sha256((const uint8_t *)buf, 43, digest);
    memcpy(iv, digest, 16);
    memset(parts, 0, sizeof(parts));
    memset(buf, 0, sizeof(buf));
    memset(digest, 0, sizeof(digest));
}

// Returns malloc'd NUL-terminated plaintext, or NULL on any failure.
// Caller frees with free(). Never returns partial/garbage data.
static char *secrets_decrypt(const uint8_t *ct, size_t ct_len, size_t *out_len) {
    if (ct == NULL || out_len == NULL) return NULL;
    if (ct_len == 0 || ct_len % 16 != 0) return NULL;

    uint8_t key[16], iv[16];
    derive_key_iv(key, iv);

    uint8_t rk[11][16];
    aes128_keyexpand(key, rk);
    memset(key, 0, sizeof(key));

    uint8_t *pt = (uint8_t *)malloc(ct_len + 1);
    if (!pt) { memset(iv, 0, sizeof(iv)); return NULL; }

    uint8_t prev[16], blk[16], dec[16];
    memcpy(prev, iv, 16);
    for (size_t b = 0; b < ct_len; b += 16) {
        memcpy(blk, ct + b, 16);
        aes128_ecb_decrypt_block(blk, dec, rk);
        for (int i = 0; i < 16; i++) pt[b + i] = dec[i] ^ prev[i];
        memcpy(prev, blk, 16);
    }
    memset(iv, 0, sizeof(iv));
    memset(prev, 0, sizeof(prev));
    memset(dec, 0, sizeof(dec));
    memset(blk, 0, sizeof(blk));
    memset(rk, 0, sizeof(rk));

    // PKCS#7 unpad with validation
    uint8_t pad = pt[ct_len - 1];
    int ok = (pad >= 1 && pad <= 16 && pad <= ct_len);
    uint8_t bad = 0;
    for (size_t i = 0; i < ct_len; i++) {
        uint8_t in_pad = (i >= ct_len - (ok ? pad : 0)) ? 1 : 0;
        bad |= in_pad & (uint8_t)(pt[i] ^ pad);
    }
    if (!ok || bad) { memset(pt, 0, ct_len); free(pt); return NULL; }
    size_t plen = ct_len - pad;
    pt[plen] = '\0';
    *out_len = plen;
    return (char *)pt;
}

