static int b64val(char c) {
    if (c >= 'A' && c <= 'Z') return c - 'A';
    if (c >= 'a' && c <= 'z') return c - 'a' + 26;
    if (c >= '0' && c <= '9') return c - '0' + 52;
    if (c == '+') return 62;
    if (c == '/') return 63;
    return -1;
}

static uint8_t *b64dec(const char *s, size_t *out_len) {
    size_t full = strlen(s);
    size_t len = (full / 4) * 3;
    if (full >= 1 && s[full - 1] == '=') len--;
    if (full >= 2 && s[full - 2] == '=') len--;
    uint8_t *out = (uint8_t *)malloc(len + 1);
    size_t o = 0;
    for (size_t i = 0; i < full; i += 4) {
        int c0 = b64val(s[i]);
        int c1 = b64val(s[i + 1]);
        int c2 = s[i + 2] == '=' ? 0 : b64val(s[i + 2]);
        int c3 = s[i + 3] == '=' ? 0 : b64val(s[i + 3]);
        int v = (c0 << 18) | (c1 << 12) | (c2 << 6) | c3;
        if (o < len) out[o++] = (uint8_t)((v >> 16) & 0xff);
        if (o < len) out[o++] = (uint8_t)((v >> 8) & 0xff);
        if (o < len) out[o++] = (uint8_t)(v & 0xff);
    }
    *out_len = len;
    return out;
}

